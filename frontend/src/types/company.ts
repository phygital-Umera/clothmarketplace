export type CompanyStatus = 'ACTIVE' | 'INACTIVE';

export interface Company {
  id: string;
  name: string;
  code: string;
  email: string;
  contactNumber: string;
  address: string;
  logo: string | null;
  country: string;
  state: string;
  district: string | null;
  city: string;
  postalCode: string;
  adminName: string;
  adminEmail: string;
  adminPhone: string;
  status: CompanyStatus;
  /** Whether the company admin already has a sign-in password */
  hasAdminLogin?: boolean;
  createdAt: string;
  updatedAt: string;
}

/** Columns the backend can sort companies by */
export const COMPANY_SORT_FIELDS = [
  'createdAt',
  'name',
  'code',
  'city',
  'status',
] as const;
export type CompanySortField = (typeof COMPANY_SORT_FIELDS)[number];

export interface CompanyListParams {
  page: number;
  limit: number;
  search?: string;
  status?: CompanyStatus;
  sortBy?: CompanySortField;
  sortDir?: 'asc' | 'desc';
}

export interface CompanyList {
  items: Company[];
  pagination: {page: number; limit: number; total: number; totalPages: number};
  summary: {total: number; active: number; inactive: number};
}

/** What the form sends; the code is generated by the backend */
export type CompanyFormValues = Omit<
  Company,
  | 'id'
  | 'code'
  | 'logo'
  | 'country'
  | 'district'
  | 'hasAdminLogin'
  | 'createdAt'
  | 'updatedAt'
> & {district: string; adminPassword?: string};

export interface CompanyPayload {
  values: CompanyFormValues;
  logo?: File | null;
  removeLogo?: boolean;
}

export interface PincodeDetails {
  pincode: string;
  state: string;
  district: string;
  city: string;
  country: string;
}
