import {
  ConfirmDialog,
  GenericDropdown,
  GenericInputField,
  GenericPasswordField,
  GenericTextArea,
} from '@/components/Forms';
import {FormError, FormFooter, FormGroup} from '@/components/ui/FormLayout';
import {useBranchOptions} from '@/lib/react-query/queriesAndMutations/org';
import {applyServerErrors} from '@/lib/validation/fieldRules';
import {
  EMPTY_SHOP,
  SHOP_FIELDS,
  shopSchema,
  ShopValues,
} from '@/lib/validation/orgSchemas';
import {Panel} from '@/types/org';
import {getErrorMessage} from '@/utils/axios';
import {zodResolver} from '@hookform/resolvers/zod';
import {useState} from 'react';
import {FormProvider, useForm} from 'react-hook-form';

type ShopFormProps = {
  panel: Panel;
  mode: 'create' | 'edit';
  defaultValues?: ShopValues;
  /** Edit only: the shop already has a login */
  hasLogin?: boolean;
  onSubmit: (values: ShopValues) => Promise<unknown>;
  onCancel: () => void;
};

/**
 * Add / edit a shop. The shop code is generated by the backend. Company
 * admins pick the branch (fixed once created); for branch admins it is their own.
 */
const ShopForm = ({
  panel,
  mode,
  defaultValues = EMPTY_SHOP,
  hasLogin,
  onSubmit,
  onCancel,
}: ShopFormProps) => {
  const pickBranch = panel === 'company-admin';
  const branches = useBranchOptions(pickBranch);
  const [formError, setFormError] = useState('');
  const [confirmLeave, setConfirmLeave] = useState(false);
  const form = useForm<ShopValues>({
    resolver: zodResolver(shopSchema({needsBranch: pickBranch})),
    defaultValues,
    mode: 'onTouched',
  });
  const {
    handleSubmit,
    setError,
    formState: {isSubmitting, isDirty},
  } = form;

  const submit = handleSubmit(async (values) => {
    setFormError('');
    try {
      await onSubmit(values);
    } catch (error) {
      if (!applyServerErrors(error, setError, SHOP_FIELDS)) {
        setFormError(getErrorMessage(error, 'Could not save the shop'));
      }
    }
  });

  return (
    <FormProvider {...form}>
      <form onSubmit={submit} noValidate className="space-y-4">
        <FormError message={formError} />

        <div className="panel space-y-5 p-4 md:p-5">
          <FormGroup title="Shop">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2 md:grid-cols-4">
              {pickBranch && (
                <GenericDropdown
                  name="branchId"
                  label="Branch"
                  required
                  disabled={mode === 'edit'}
                  hint={
                    mode === 'edit' ? 'A shop stays in its branch.' : undefined
                  }
                  loading={branches.isPending}
                  options={branches.data ?? []}
                  placeholder="Select branch"
                />
              )}
              <GenericInputField
                name="name"
                label="Shop Name"
                kind="text"
                required
                autoFocus={mode === 'create'}
                placeholder="Ladies Wear Counter"
              />
              <GenericInputField name="email" label="Shop Email" kind="email" />
              <GenericInputField
                name="phone"
                label="Contact Phone"
                kind="phone"
                prefix="+91"
              />
              <GenericInputField
                name="address"
                label="Address / Floor"
                kind="text"
                maxLength={500}
                placeholder="1st floor, left wing"
                className="sm:col-span-2 md:col-span-2"
              />
              <GenericInputField
                name="gstin"
                label="GSTIN"
                kind="gstin"
                placeholder="27ABCDE1234F1Z5"
              />
              <GenericInputField
                name="billPrefix"
                label="Bill Prefix"
                kind="text"
                maxLength={6}
                placeholder="WW"
                hint="Sales bills: WW/26-27/00001"
              />
            </div>
          </FormGroup>

          <FormGroup title="Hours">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2 md:grid-cols-4">
              <GenericInputField
                name="openingTime"
                label="Opening Time"
                type="time"
              />
              <GenericInputField
                name="closingTime"
                label="Closing Time"
                type="time"
              />
              {/* On edit, status changes use Activate / Deactivate (with a reason) */}
              {mode === 'create' && (
                <GenericDropdown
                  name="status"
                  label="Status"
                  required
                  options={[
                    {value: 'ACTIVE', label: 'Active'},
                    {value: 'INACTIVE', label: 'Inactive'},
                  ]}
                />
              )}
            </div>
          </FormGroup>

          <FormGroup title="Shop Login">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2 md:grid-cols-4">
              <GenericInputField
                name="adminName"
                label="Full Name"
                kind="name"
                placeholder="Sunita Patil"
              />
              <GenericInputField
                name="adminPhone"
                label="Phone Number"
                kind="phone"
                prefix="+91"
              />
              <GenericInputField name="adminEmail" label="Email" kind="email" />
              <GenericPasswordField
                name="adminPassword"
                label="Password"
                hint={
                  hasLogin
                    ? 'Leave blank to keep the current password.'
                    : 'The shop signs in with this phone and password.'
                }
              />
            </div>
          </FormGroup>

          <GenericTextArea
            name="notes"
            label="Notes"
            rows={2}
            maxLength={500}
          />
        </div>

        <FormFooter
          onCancel={() => (isDirty ? setConfirmLeave(true) : onCancel())}
          saving={isSubmitting}
          saveLabel={mode === 'create' ? 'Save Shop' : 'Save Changes'}
        />

        <ConfirmDialog
          open={confirmLeave}
          title="Discard changes?"
          message="You have unsaved changes on this form. Leaving now will lose them."
          confirmLabel="Discard"
          tone="danger"
          onConfirm={onCancel}
          onCancel={() => setConfirmLeave(false)}
        />
      </form>
    </FormProvider>
  );
};

export default ShopForm;
