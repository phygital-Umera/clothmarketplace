import {
  ConfirmDialog,
  GenericDatePicker,
  GenericDropdown,
  GenericInputField,
  GenericPasswordField,
} from '@/components/Forms';
import {FormError, FormFooter, FormGroup} from '@/components/ui/FormLayout';
import {
  useBranchOptions,
  useShopOptions,
} from '@/lib/react-query/queriesAndMutations/org';
import {applyServerErrors} from '@/lib/validation/fieldRules';
import {
  EMPLOYEE_FIELDS,
  employeeSchema,
  EmployeeValues,
  EMPTY_EMPLOYEE,
} from '@/lib/validation/orgSchemas';
import {Panel} from '@/types/org';
import ModuleAccessField from '@/components/Org/ModuleAccessField';
import {getErrorMessage} from '@/utils/axios';
import {zodResolver} from '@hookform/resolvers/zod';
import {useState} from 'react';
import {FormProvider, useForm, useWatch} from 'react-hook-form';

type EmployeeFormProps = {
  panel: Panel;
  mode: 'create' | 'edit';
  defaultValues?: EmployeeValues;
  onSubmit: (values: EmployeeValues) => Promise<unknown>;
  onCancel: () => void;
};

/**
 * Add / edit an employee. The Employee ID is generated by the backend.
 * Every employee works in a shop. Company admins with more than one active
 * branch pick the branch, then one of its shops; with one branch they pick
 * from all their shops (the backend takes the branch from the shop). Branch
 * admins pick a shop of their own branch.
 */
const EmployeeForm = ({
  panel,
  mode,
  defaultValues = EMPTY_EMPLOYEE,
  onSubmit,
  onCancel,
}: EmployeeFormProps) => {
  const companyWide = panel === 'company-admin';
  // A shop login adds employees to its own shop only
  const pickShop = panel !== 'shop-admin';
  const branches = useBranchOptions(companyWide);
  const pickBranch = companyWide && (branches.data?.length ?? 0) > 1;
  // Wait for the branch count before loading shops, so the list does not flip
  const branchesKnown = !companyWide || !branches.isPending;
  const [formError, setFormError] = useState('');
  const [confirmLeave, setConfirmLeave] = useState(false);
  const form = useForm<EmployeeValues>({
    resolver: zodResolver(
      employeeSchema({
        create: mode === 'create',
        needsBranch: pickBranch,
        needsShop: pickShop,
      }),
    ),
    defaultValues,
    mode: 'onTouched',
  });
  const {
    handleSubmit,
    setError,
    control,
    formState: {isSubmitting, isDirty},
  } = form;
  const branchId = useWatch({control, name: 'branchId'});
  const needsBranchFirst = pickBranch && !branchId;
  const shops = useShopOptions(
    panel,
    pickBranch ? branchId : undefined,
    pickShop && branchesKnown && !needsBranchFirst,
  );

  const submit = handleSubmit(async (values) => {
    setFormError('');
    try {
      // Branch picker hidden (one branch): send no branch, the server takes it from the shop
      await onSubmit(
        companyWide && !pickBranch ? {...values, branchId: ''} : values,
      );
    } catch (error) {
      if (!applyServerErrors(error, setError, EMPLOYEE_FIELDS)) {
        setFormError(getErrorMessage(error, 'Could not save the employee'));
      }
    }
  });

  return (
    <FormProvider {...form}>
      <form onSubmit={submit} noValidate className="space-y-4">
        <FormError message={formError} />

        <div className="panel space-y-5 p-4 md:p-5">
          <FormGroup title="Employee">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2 md:grid-cols-3">
              <GenericInputField
                name="fullname"
                label="Full Name"
                kind="name"
                required
                autoFocus={mode === 'create'}
              />
              <GenericInputField
                name="email"
                label="Email"
                kind="email"
                required
              />
              <GenericInputField
                name="phoneNumber"
                label="Phone Number"
                kind="phone"
                prefix="+91"
                required
              />
            </div>
          </FormGroup>

          <FormGroup title="Work">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2 md:grid-cols-4">
              {pickBranch && (
                <GenericDropdown
                  name="branchId"
                  label="Assigned Branch"
                  required
                  loading={branches.isPending}
                  options={branches.data ?? []}
                  placeholder="Select branch"
                />
              )}
              {pickShop && (
                <GenericDropdown
                  name="shopId"
                  label="Assigned Shop"
                  required
                  dependsOn={pickBranch ? 'branchId' : undefined}
                  disabled={needsBranchFirst}
                  loading={!needsBranchFirst && shops.isPending}
                  options={shops.data ?? []}
                  placeholder={
                    needsBranchFirst ? 'Select branch first' : 'Select shop'
                  }
                  hint={
                    !needsBranchFirst && shops.data?.length === 0
                      ? 'No active shop here yet. Add one under Shops.'
                      : undefined
                  }
                />
              )}
              <GenericInputField
                name="employeeRole"
                label="Employee Role"
                kind="text"
                placeholder="e.g. Store Manager, Cashier"
              />
              <GenericInputField
                name="jobTitle"
                label="Job Title"
                kind="text"
                placeholder="Sales Associate"
              />
              <GenericInputField
                name="department"
                label="Department"
                kind="text"
                placeholder="Sales"
              />
              <GenericDatePicker name="joiningDate" label="Joining Date" />
            </div>
          </FormGroup>

          <FormGroup title="Login">
            <div className="grid gap-x-4 gap-y-3 sm:grid-cols-2">
              <p className="self-center text-body-sm text-on-surface-variant">
                The employee signs in with their phone number (or email) and
                this password.
              </p>
              <GenericPasswordField
                name="password"
                label="Password"
                required={mode === 'create'}
                hint={
                  mode === 'create'
                    ? 'They must change it at first sign-in.'
                    : 'Leave blank to keep the current password.'
                }
              />
            </div>
          </FormGroup>

          <FormGroup title="Access">
            <ModuleAccessField />
          </FormGroup>
        </div>

        <FormFooter
          onCancel={() => (isDirty ? setConfirmLeave(true) : onCancel())}
          saving={isSubmitting}
          saveLabel={mode === 'create' ? 'Save Employee' : 'Save Changes'}
        />

        <ConfirmDialog
          open={confirmLeave}
          title="Discard changes?"
          message="You have unsaved changes on this form. Leaving now will lose them."
          confirmLabel="Discard"
          tone="danger"
          onConfirm={onCancel}
          onCancel={() => setConfirmLeave(false)}
        />
      </form>
    </FormProvider>
  );
};

export default EmployeeForm;
